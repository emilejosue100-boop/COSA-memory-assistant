import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const backendUrl = (process.env.BACKEND_URL || process.env.VITE_API_URL || '')
  .trim()
  .replace(/\/$/, '');

console.log(
  `[vercel] prebuild: BACKEND_URL=${backendUrl || '(not set — API proxy will be disabled unless set before postbuild)'}`
);

// Client build flag — used to hide/show misconfiguration banner in the UI.
const proxyFlagPath = path.join(frontendRoot, 'src', 'generated');
fs.mkdirSync(proxyFlagPath, { recursive: true });
fs.writeFileSync(
  path.join(proxyFlagPath, 'apiProxy.ts'),
  `// Auto-generated by scripts/generate-vercel-config.mjs — do not edit\nexport const HAS_API_PROXY = ${backendUrl ? 'true' : 'false'};\n`
);

// NOTE: Do not write rewrites into vercel.json here. Vercel reads project routing
// configuration before the build runs; mutating vercel.json during prebuild is too
// late. API proxy routes are emitted in postbuild via .vercel/output/config.json
// (see scripts/finalize-vercel-output.mjs).
